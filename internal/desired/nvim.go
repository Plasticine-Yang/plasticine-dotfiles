func neovimPlugins() string {
	return strings.Join([]string{
		"local ensure_packer = function()",
		"  local fn = vim.fn",
		"  local install_path = fn.stdpath('data') .. '/site/pack/packer/start/packer.nvim'",
		"  if fn.empty(fn.glob(install_path)) > 0 then",
		"    vim.notify('installing packer.nvim...')",
		"    fn.system({ 'git', 'clone', '--depth', '1', 'https://github.com/wbthomason/packer.nvim', install_path })",
		"    vim.cmd [[packadd packer.nvim]]",
		"    return true",
		"  end",
		"  return false",
		"end",
		"",
		"local packer_bootstrap = ensure_packer()",
		"local status_ok, packer = pcall(require, 'packer')",
		"if not status_ok then",
		"  vim.notify('packer.nvim is not installed!')",
		"  return",
		"end",
		"",
		"packer.startup({",
		"  function(use)",
		"    use 'wbthomason/packer.nvim'",
		"    use 'folke/tokyonight.nvim'",
		"    use 'karb94/neoscroll.nvim'",
		"    use 'ur4ltz/surround.nvim'",
		"    use({ 'windwp/nvim-autopairs', config = function() require('nvim-autopairs').setup({}) end })",
		"    use({ 'phaazon/hop.nvim', branch = 'v2', config = function() require('hop').setup({ keys = 'etovxqpdygfblzhckisuran' }) end })",
		"    use({ 'nvim-tree/nvim-tree.lua', requires = { 'nvim-tree/nvim-web-devicons' }, config = function() require('plugins-config.nvim-tree') end })",
		"    use({ 'akinsho/toggleterm.nvim', tag = '*', config = function() require('plugins-config.toggleterm') end })",
		"    if packer_bootstrap then require('packer').sync() end",
		"  end,",
		"  config = { display = { open_fn = require('packer.util').float } }",
		"})",
		"pcall(vim.cmd, [[",
		"  augroup packer_user_config",
		"    autocmd!",
		"    autocmd BufWritePost plugins.lua source <afile> | PackerSync",
		"  augroup end",
		"]])",
		"",
	}, "\n")
}

