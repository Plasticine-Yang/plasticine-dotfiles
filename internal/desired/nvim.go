package desired

import "strings"

type ConfigFile struct {
	Path    string
	Content string
}

func NeovimConfigFiles() []ConfigFile {
	return []ConfigFile{
		{Path: "init.lua", Content: neovimInit()},
		{Path: "lua/basic.lua", Content: neovimBasic()},
		{Path: "lua/keybindings.lua", Content: neovimKeybindings()},
		{Path: "lua/colorschema.lua", Content: neovimColorscheme()},
		{Path: "lua/plugins.lua", Content: neovimPlugins()},
		{Path: "lua/plugins-config/neoscroll.lua", Content: neovimNeoscrollConfig()},
		{Path: "lua/plugins-config/nvim-tree.lua", Content: neovimTreeConfig()},
		{Path: "lua/plugins-config/surround.lua", Content: neovimSurroundConfig()},
		{Path: "lua/plugins-config/toggleterm.lua", Content: neovimToggletermConfig()},
	}
}

